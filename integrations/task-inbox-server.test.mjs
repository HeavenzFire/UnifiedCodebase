import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createTaskInboxServer } from './task-inbox-server.mjs';

function proposal(taskId = 'proposal-1', overrides = {}) {
  const stamp = '2026-10-31T20:00:00.000Z';
  return {
    schema: 'heavenzfire.shared-task.v1', taskId, source: 'continuous-rd-pipeline',
    goal: 'Verify a bounded local integration task', status: 'proposed', approvalState: 'pending',
    evidence: [{
      kind: 'proposal', summary: 'Generated by an explicit local research cycle',
      sourceUrl: null, observedAt: stamp, actor: 'local-rd-pipeline'
    }],
    createdAt: stamp, updatedAt: stamp,
    metadata: { cycle: 1, promptSha256: 'a'.repeat(64), promptChars: 42 },
    ...overrides,
  };
}
async function withInbox(t, options = {}) {
  const directory = mkdtempSync(join(tmpdir(), 'hf-task-inbox-'));
  const filePath = join(directory, 'state', 'inbox.jsonl');
  const inbox = createTaskInboxServer({ filePath, ...options });
  const address = await inbox.listen(0);
  t.after(async () => {
    await inbox.close();
    rmSync(directory, { recursive: true, force: true });
  });
  return { inbox, filePath, endpoint: 'http://127.0.0.1:' + address.port };
}
async function post(endpoint, body) {
  return fetch(endpoint + '/api/tasks', {
    method: 'POST', headers: { 'content-type': 'application/json' },
    body: typeof body === 'string' ? body : JSON.stringify(body),
  });
}

test('accepts and durably records a proposed/pending task on loopback', async t => {
  const { inbox, filePath, endpoint } = await withInbox(t, { now: () => '2026-10-31T20:01:00.000Z' });
  const response = await post(endpoint, { taskRecord: proposal() });
  assert.equal(response.status, 201);
  assert.deepEqual(await response.json(), {
    ok: true, duplicate: false, taskId: 'proposal-1', status: 'proposed', approvalState: 'pending'
  });
  assert.equal(inbox.health().entries, 1);
  const lines = readFileSync(filePath, 'utf8').trim().split('\n');
  assert.equal(lines.length, 1);
  assert.equal(JSON.parse(lines[0]).taskRecord.taskId, 'proposal-1');
  const health = await fetch(endpoint + '/health');
  assert.equal((await health.json()).executionEnabled, false);
  const listing = await (await fetch(endpoint + '/api/tasks')).json();
  assert.equal(listing.total, 1);
  assert.equal(listing.tasks[0].taskId, 'proposal-1');
  assert.equal(Object.prototype.hasOwnProperty.call(listing.tasks[0], 'metadata'), false);
});

test('identical duplicate delivery is idempotent and conflicting task IDs are rejected', async t => {
  const { endpoint, inbox } = await withInbox(t);
  assert.equal((await post(endpoint, { taskRecord: proposal() })).status, 201);
  const duplicate = await post(endpoint, { taskRecord: proposal() });
  assert.equal(duplicate.status, 200);
  assert.equal((await duplicate.json()).duplicate, true);
  const conflict = await post(endpoint, { taskRecord: proposal('proposal-1', { goal: 'Different request under same ID' }) });
  assert.equal(conflict.status, 409);
  assert.equal((await conflict.json()).error, 'task_id_conflict');
  assert.equal(inbox.health().entries, 1);
});

test('concurrent duplicate deliveries produce one journal entry', async t => {
  const { endpoint, inbox } = await withInbox(t);
  const results = await Promise.all([
    post(endpoint, { taskRecord: proposal('concurrent-1') }),
    post(endpoint, { taskRecord: proposal('concurrent-1') }),
  ]);
  assert.deepEqual(results.map(r => r.status).sort(), [200, 201]);
  assert.equal(inbox.health().entries, 1);
});

test('rejects approved, malformed, unsupported, and oversized requests', async t => {
  const { endpoint } = await withInbox(t, { maxBodyBytes: 2048 });
  const approved = proposal('approved-1', { status: 'approved', approvalState: 'approved' });
  assert.equal((await post(endpoint, { taskRecord: approved })).status, 422);
  assert.equal((await post(endpoint, { taskRecord: { ...proposal(), extra: true } })).status, 422);
  assert.equal((await post(endpoint, '{bad-json')).status, 400);
  const tooLarge = await post(endpoint, { taskRecord: proposal('large-1', { metadata: { blob: 'x'.repeat(3000) } }) });
  assert.equal(tooLarge.status, 413);
  assert.equal((await fetch(endpoint + '/api/tasks?limit=nope')).status, 400);
});

test('refuses non-loopback bind configuration and a second writer for the same journal', async t => {
  assert.throws(() => createTaskInboxServer({ filePath: '/tmp/unused-inbox.jsonl', host: '0.0.0.0' }), /only to 127.0.0.1/);
  const directory = mkdtempSync(join(tmpdir(), 'hf-task-inbox-lock-'));
  const filePath = join(directory, 'inbox.jsonl');
  const first = createTaskInboxServer({ filePath });
  const heldLock = readFileSync(filePath + '.lock', 'utf8');
  assert.throws(() => createTaskInboxServer({ filePath }), /already locked/);
  assert.equal(readFileSync(filePath + '.lock', 'utf8'), heldLock, 'failed second writer must not remove the active lock');
  await first.close();
  const second = createTaskInboxServer({ filePath });
  await second.close();
  rmSync(directory, { recursive: true, force: true });
});

test('replays a valid journal and fails closed on tampering or partial records', async t => {
  const first = await withInbox(t);
  await post(first.endpoint, { taskRecord: proposal('replay-1') });
  await first.inbox.close();
  const restarted = createTaskInboxServer({ filePath: first.filePath });
  assert.equal(restarted.health().entries, 1);
  await restarted.close();
  const entry = JSON.parse(readFileSync(first.filePath, 'utf8').trim());
  entry.taskRecord.goal = 'tampered';
  writeFileSync(first.filePath, JSON.stringify(entry) + '\n', 'utf8');
  assert.throws(() => createTaskInboxServer({ filePath: first.filePath }), /hash mismatch/);
  writeFileSync(first.filePath, '{"partial":', 'utf8');
  assert.throws(() => createTaskInboxServer({ filePath: first.filePath }), /incomplete final record/);
});
